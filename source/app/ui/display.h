/*
 * Display dimension in pixels, this much match those in the hardware
 * IO driver.  Repeated to avoid leaking SPI/CMSIS headers
 * into app space from using include.
 */
#define DISPLAY_PANEL_PX_WIDTH (320)
#define DISPLAY_PANEL_PX_HEIGHT (240)

/*
 * Size of cell (character) in the display - the font's native, unscaled
 * cell. No stretching: the font table (font/font_ui.c, generated by one of
 * the font/<font>/make_font.py scripts) is drawn at its own pixel size,
 * 16x24.
 */
#define DISPLAY_CELL_W (FONT_CELL_W)
#define DISPLAY_CELL_H (FONT_CELL_H)

/*
 * Display dimensions in characters - as many whole cells as fit the
 * panel.  A 16x24 cell divides the 320x240 panel exactly (20 x 10).  With
 * any other cell size the unused margin is cleared to black once at boot by
 * lcd_chip_init(), not by the row-by-row updates this module drives.
 */
#define DISPLAY_COLS (DISPLAY_PANEL_PX_WIDTH / DISPLAY_CELL_W) 
#define DISPLAY_ROWS (DISPLAY_PANEL_PX_HEIGHT / DISPLAY_CELL_H) 


/*
 * Dimension of a single display row in pixels
 */
#define DISPLAY_ROW_PX_WIDTH (DISPLAY_COLS * DISPLAY_CELL_W)
#define DISPLAY_ROW_PX_HEIGHT (DISPLAY_ROWS * DISPLAY_CELL_H)

